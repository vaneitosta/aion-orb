const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(pathToFileURL(path.resolve('index.html')).href);
 await page.locator('#prompt').fill('tarefa: validar interface');
 await page.locator('#form').evaluate(el=>el.requestSubmit());
 await page.waitForTimeout(1100);
 await page.locator('[data-panel="metas"]').click();
 assert.match(await page.locator('#panelText').innerText(),/validar interface/);
 await page.locator('#closePanel').click();
 await page.locator('#prompt').fill('nota: teste navegador');
 await page.locator('#form').evaluate(el=>el.requestSubmit());
 await page.waitForTimeout(1100);
 await page.locator('[data-panel="projetos"]').click();
 assert.match(await page.locator('#panelText').innerText(),/teste navegador/);
 await page.locator('#closePanel').click();
 await page.locator('[data-panel="config"]').click();
 await page.locator('#panelAction').click();
 assert.equal(await page.locator('body').getAttribute('data-reduced'),'true');
 await page.locator('#closePanel').click();
 await page.locator('[data-mode="thinking"]').click();
 assert.equal(await page.locator('body').getAttribute('data-mode'),'thinking');
 const horizontalOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2);
 assert.equal(horizontalOverflow,false,'Horizontal overflow on mobile');
 await page.screenshot({path:'aion-mobile-test.png',fullPage:true});
 assert.deepEqual(errors,[],'Browser console page errors');
 await browser.close();console.log('Chromium mobile browser checks: PASS');
})().catch(e=>{console.error(e);process.exitCode=1});
